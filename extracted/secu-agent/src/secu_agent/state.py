_TODO_STATUSES = {"pending", "in_progress", "completed", "cancelled", "blocked"}


def _todo_normalize_status(s: Any) -> str:
    v = str(s or "pending").strip().lower()
    return v if v in _TODO_STATUSES else "pending"


def _todo_dedupe(items: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """같은 item_id 두번이면 마지막 것만."""
    last: dict[str, int] = {}
    for i, it in enumerate(items):
        iid = str(it.get("id", "")).strip() or "?"
        last[iid] = i
    return [items[i] for i in sorted(last.values())]


def _todo_row(r) -> dict[str, Any]:
    return {
        "id": r["item_id"], "content": r["content"], "status": r["status"],
        "position": r["position"],
        "created_at": r["created_at"], "updated_at": r["updated_at"],
    }


def todo_read(session_id: int) -> list[dict[str, Any]]:
    with connect() as c:
        rows = c.execute(
            "SELECT * FROM chat_todo WHERE session_id=? "
            "ORDER BY position ASC, id ASC",
            (session_id,),
        ).fetchall()
        return [_todo_row(r) for r in rows]


def todo_write(
    session_id: int, *, todos: list[dict[str, Any]], merge: bool = False,
) -> list[dict[str, Any]]:
    """todos write. replace (default) 또는 merge.
    Returns: 영속 후 전체 list.
    """
    todos = _todo_dedupe([t for t in todos if t])
    now = time.time()
    with connect() as c:
        if not merge:
            c.execute("DELETE FROM chat_todo WHERE session_id=?", (session_id,))
            for pos, t in enumerate(todos):
                iid = str(t.get("id", "")).strip() or "?"
                content = str(t.get("content", "")).strip() or "(no description)"
                status = _todo_normalize_status(t.get("status"))
                c.execute(
                    "INSERT INTO chat_todo(session_id, item_id, content, "
                    "status, position, created_at, updated_at) "
                    "VALUES (?, ?, ?, ?, ?, ?, ?)",
                    (session_id, iid, content, status, pos, now, now),
                )
        else:
            existing = {
                r["item_id"]: r for r in c.execute(
                    "SELECT * FROM chat_todo WHERE session_id=?",
                    (session_id,),
                ).fetchall()
            }
            max_pos = max(
                (r["position"] for r in existing.values()), default=-1,
            )
            for t in todos:
                iid = str(t.get("id", "")).strip() or "?"
                if iid in existing:
                    sets: list[str] = []
                    args: list[Any] = []
                    if "content" in t and t.get("content"):
                        sets.append("content=?")
                        args.append(str(t["content"]).strip())
                    if "status" in t and t.get("status") is not None:
                        sets.append("status=?")
                        args.append(_todo_normalize_status(t["status"]))
                    if sets:
                        sets.append("updated_at=?")
                        args.append(now)
                        args.extend([session_id, iid])
                        c.execute(
                            f"UPDATE chat_todo SET {', '.join(sets)} "
                            f"WHERE session_id=? AND item_id=?", args,
                        )
                else:
                    max_pos += 1
                    content = str(t.get("content", "")).strip() or "(no description)"
                    status = _todo_normalize_status(t.get("status"))
                    c.execute(
                        "INSERT INTO chat_todo(session_id, item_id, content, "
                        "status, position, created_at, updated_at) "
                        "VALUES (?, ?, ?, ?, ?, ?, ?)",
                        (session_id, iid, content, status, max_pos, now, now),
                    )
    return todo_read(session_id)


def todo_clear(session_id: int) -> None:
    with connect() as c:
        c.execute("DELETE FROM chat_todo WHERE session_id=?", (session_id,))


