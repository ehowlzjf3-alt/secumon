def _pg_pool_wait_warn_sec() -> float:
    """checkout 대기 경고 임계(초). 0 이면 비활성. env 로 매번 조회(운영 중 튜닝)."""
    return _env_float("SA_PG_POOL_WAIT_WARN_SEC", _PG_POOL_WAIT_WARN_SEC_DEFAULT)


def _pg_pool():
    """프로세스 단위 psycopg 커넥션 풀 (호출당 핸드셰이크 회피)."""
    global _PG_POOL
    if _PG_POOL is None:
        from psycopg_pool import ConnectionPool
        max_size = _env_int("SA_PG_POOL_MAX_SIZE", _PG_POOL_MAX_SIZE_DEFAULT)
        min_size = _env_int("SA_PG_POOL_MIN_SIZE", _PG_POOL_MIN_SIZE_DEFAULT)
        if min_size > max_size:
            log.warning(
                "SA_PG_POOL_MIN_SIZE=%d > max_size=%d — min 을 max 로 clamp",
                min_size, max_size,
            )
            min_size = max_size
        _PG_POOL = ConnectionPool(
            _pg_dsn(), min_size=min_size, max_size=max_size, open=True,
            kwargs={"autocommit": True},
            configure=_pg_configure,
            reset=_pg_reset,
        )
    return _PG_POOL


def _pg_configure(conn) -> None:
    """v3.88: 새 물리커넥션마다 baseline invariant 고정 — search_path + lock_timeout=0 (reset 와 동일).
    core 미존재 시에도 합법. 실패는 삼키지 않는다(R2: psycopg_pool 이 불량 커넥션 폐기).
    함수는 pg_catalog 한정 — 오염 스키마의 동명 함수 shadowing 차단(codex R2)."""
    conn.execute(
        "SELECT pg_catalog.set_config('search_path', %s, false), "
        "pg_catalog.set_config('lock_timeout', '0', false)",
        (_BASELINE_SEARCH_PATH,),
    )


def _pg_reset(conn) -> None:
    """v3.88 R2-2/R2-3: check-in 마다 세션 상태 재정규화 — baseline search_path + lock_timeout=0 +
    누수 session-level advisory lock 해제(bootstrap/apply_schema 의 SET·lock 잔류 봉쇄, 비대칭 해소).
    한 round-trip. reset 이 raise 하면 psycopg_pool 이 그 물리 커넥션을 폐기(오염 전파 차단, R2-3).
    ★ 모든 함수를 pg_catalog 로 한정 — reset 은 '이전 borrower 의 (오염 가능) search_path' 에서 돌기
    때문에, 비한정이면 함수 OID 가 SET 前에 해석돼 evil.set_config/evil.pg_advisory_unlock_all 로
    shadow 될 수 있다(codex R2). raw 접근 계약: 호출자는 search_path·lock_timeout·advisory lock 외
    세션 상태(SET ROLE/statement_timeout/LISTEN 등)를 남기지 말 것(그건 이 reset 범위 밖)."""
    conn.execute(
        "SELECT pg_catalog.set_config('search_path', %s, false), "
        "pg_catalog.set_config('lock_timeout', '0', false), pg_catalog.pg_advisory_unlock_all()",
        (_BASELINE_SEARCH_PATH,),
    )


