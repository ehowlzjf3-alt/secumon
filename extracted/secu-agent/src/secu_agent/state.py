# session_search — cross-session 통합 검색 (trigram 부분일치)
# de-domain v3.84 #4: kind 는 개방형 — 코어는 memory_rule 만 색인하고, 도메인 kind
# (file_review/share_review 등)는 도메인 어댑터가 색인/질의한다. finding_index 스키마의
# share_* 컬럼(도메인 색인 소관)을 generic 화하는 것은 별도 조정된 마이그레이션.
# ============================================================

def _fts_delete(c, kind: str, ref_id: int) -> None:
    c.execute("DELETE FROM finding_index WHERE kind=? AND ref_id=?",
              (kind, ref_id))


def _reindex_memory_rule(c, mid: int,
                         scope: str, key: str, rule: str) -> None:
    _fts_delete(c, "memory_rule", mid)
    content = f"[{scope}:{key}] {rule}"
    c.execute(
        "INSERT INTO finding_index(kind, ref_id, share_id, host, share_name, "
        "path, content) VALUES (?, ?, ?, ?, ?, ?, ?)",
        ("memory_rule", mid, None, None, None, "", content),
    )


def _session_search_pg(
    q: str, kind: str | None, exclude_share_id: int | None, limit: int,
) -> list[dict[str, Any]]:
    """postgres 변종 — pg_trgm 부분일치(ILIKE). FTS5 trigram 과 의미 동등."""
    esc = q.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")
    like = f"%{esc}%"
    where = ["(coalesce(path,'')||' '||coalesce(content,'')) ILIKE ?"]
    args: list[Any] = [like]
    if kind:
        where.append("kind=?")
        args.append(kind)
    if exclude_share_id is not None:
        where.append("(share_id IS NULL OR share_id != ?)")
        args.append(exclude_share_id)
    sql = (
        "SELECT kind, ref_id, share_id, host, share_name, path, content "
        "FROM finding_index WHERE " + " AND ".join(where)
        + " ORDER BY ref_id DESC LIMIT ?"
    )
    args.append(limit)
    with connect() as c:
        try:
            rows = c.execute(sql, args).fetchall()
        except Exception:
            return []
        result = []
        for r in rows:
            d = {k: r[k] for k in r.keys()}
            d["ref_id"] = int(d["ref_id"]) if d["ref_id"] is not None else None
            d["share_id"] = int(d["share_id"]) if d["share_id"] is not None else None
            result.append(d)
        return result


def session_search(
    query: str, *,
    kind: str | None = None,
    exclude_share_id: int | None = None,
    limit: int = 20,
) -> list[dict[str, Any]]:
    """cross-session 통합 검색 — pg_trgm 부분일치(ILIKE). 한글 부분 매칭 OK.

    kind 필터: 개방형 문자열 (코어는 memory_rule 색인, 도메인 kind 는 어댑터 소관).
    exclude_share_id: scope 소유자가 자기 scope 빼고 cross-scope 검색 시 (도메인 배선).
    """
    q = query.strip()
    if not q:
        return []
    return _session_search_pg(q, kind, exclude_share_id, limit)


# ── finding_index row 위치 렌더러 (v3.85: 등록형) ────────────────────────────
# session_search_tool 이 검색결과 row 의 "위치"를 사람용으로 렌더할 때, 이전엔
# host/share_name(SMB 어휘)을 하드코딩했다. 코어는 도메인 색인 컬럼의 의미를 모르므로
# kind 별 렌더러를 도메인이 등록한다. 미등록 kind(코어 memory_rule 등)=위치 없음.
# (finding_index 의 SMB 컬럼 share_id/host/share_name strip + SCHEMA_VERSION bump 은
# 코어+도메인 색인기 동시 마이그가 필요 — 별도 coordinated 작업.)
_INDEX_RENDERERS: dict[str, Any] = {}


def register_index_renderer(kind: str, fn: Any) -> None:
    """finding_index row(kind) → 위치 문자열 렌더러 등록 (plugin API). 중복=명시 에러.

    fn(row: dict) -> str. 도메인이 자기 색인 kind(file_review/share_review 등)의
    위치를 렌더한다 — 코어는 host/share_name 같은 도메인 컬럼 의미를 모른다.
    """
    k = str(kind or "").strip()
    if not k:
        raise ValueError("index renderer kind 비어 있음")
    if k in _INDEX_RENDERERS:
        raise ValueError(f"index renderer {k!r} 이미 등록됨")
    _INDEX_RENDERERS[k] = fn


def unregister_index_renderer(kind: str) -> bool:
    return _INDEX_RENDERERS.pop(str(kind or ""), None) is not None


def render_index_location(row: dict[str, Any]) -> str:
    """등록된 kind 렌더러로 row 위치 렌더 (미등록/실패=빈 문자열, 도메인-프리)."""
    fn = _INDEX_RENDERERS.get(str(row.get("kind") or ""))
    if fn is None:
        return ""
    try:
        return str(fn(row) or "")
    except Exception:
        return ""


# ============================================================
# memory_rule — 영속 룰 (scope 는 등록형)
# de-domain v3.84 #5: 코어 base scope = {global, operator} (agent 오케스트레이션
# 중립). 도메인 scope(host/share/path_pattern 등)는 plugin 이 register_memory_scope
# 로 등록한다. 이전엔 코어가 SMB 어휘(host/share/path_pattern)를 화이트리스트로
# 강제해, 다른 도메인 어댑터가 자기 scope(repo/space_key 등)로 memory 를 저장하려
# 하면 거부됐다 — 코어가 점검 도메인을 능동 강제하던 누출.
# severity_hint ∈ {critical, high, medium, low, clean, informational}
# ============================================================

_CORE_MEMORY_SCOPES: frozenset[str] = frozenset({"global", "operator"})
_PLUGIN_MEMORY_SCOPES: set[str] = set()
_MEMORY_SEVERITIES = {"critical", "high", "medium", "low", "clean", "informational"}


def register_memory_scope(key: str) -> None:
    """도메인 memory scope 등록 (plugin 부트스트랩용). set add — 멱등."""
    k = str(key or "").strip()
    if not k:
        raise ValueError("memory scope 이름 비어 있음")
    if k not in _CORE_MEMORY_SCOPES:
        _PLUGIN_MEMORY_SCOPES.add(k)


def unregister_memory_scope(key: str) -> bool:
    """등록 해제 (테스트/재부착 멱등용). 코어 base 는 제거 불가."""
    if key in _CORE_MEMORY_SCOPES:
        return False
    if key in _PLUGIN_MEMORY_SCOPES:
        _PLUGIN_MEMORY_SCOPES.discard(key)
        return True
    return False


def valid_memory_scopes() -> frozenset[str]:
    return frozenset(_CORE_MEMORY_SCOPES | _PLUGIN_MEMORY_SCOPES)


def _memory_row(r) -> dict[str, Any]:
    d = {k: r[k] for k in r.keys()}
    d["tags"] = json.loads(d["tags"]) if d.get("tags") else []
    return d


def memory_add(
    *, scope: str, key: str, rule: str,
    severity_hint: str | None = None,
    tags: list[str] | None = None,
    source: str = "master_agent",
    expires_at: float | None = None,
) -> int:
    """같은 (scope, key) 면 update — upsert. 새거면 insert."""
    if scope not in valid_memory_scopes():
        raise ValueError(
            f"invalid scope: {scope} (유효: {sorted(valid_memory_scopes())} — "
            "도메인 scope 는 register_memory_scope 로 등록해야 함)"
        )
    if severity_hint is not None and severity_hint not in _MEMORY_SEVERITIES:
        raise ValueError(f"invalid severity_hint: {severity_hint}")
    if not rule.strip():
        raise ValueError("rule must not be empty")
    now = time.time()
    tags_json = json.dumps(tags or [], ensure_ascii=False)
    with connect() as c:
        row = c.execute(
            "SELECT id FROM memory_rule WHERE scope=? AND key=?",
            (scope, key),
        ).fetchone()
        if row:
            mid = int(row["id"])
            c.execute(
                "UPDATE memory_rule SET rule=?, severity_hint=?, tags=?, "
                "source=?, updated_at=?, expires_at=? WHERE id=?",
                (rule, severity_hint, tags_json, source, now, expires_at, mid),
            )
            _reindex_memory_rule(c, mid, scope, key, rule)
            return mid
        cur = c.execute(
            "INSERT INTO memory_rule(scope, key, rule, severity_hint, tags, "
            "source, created_at, updated_at, expires_at) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
            (scope, key, rule, severity_hint, tags_json, source,
             now, now, expires_at),
        )
        mid = int(cur.lastrowid)
        _reindex_memory_rule(c, mid, scope, key, rule)
        return mid


