def _ensure_schema_version(conn) -> None:
    target = SCHEMA_VERSION
    conn.execute(
        "INSERT INTO state_meta(key, value, updated_at) VALUES (?, ?, ?) "
        "ON CONFLICT(key) DO UPDATE SET "
        "value=excluded.value, updated_at=excluded.updated_at",
        ("schema_version", str(target), time.time()),
    )


class _PgRow:
    """sqlite3.Row 호환 — 정수 인덱스 + 컬럼명 둘 다 접근. (state.py 가 둘 다 씀)"""

    __slots__ = ("_cols", "_vals")

    def __init__(self, cols: tuple[str, ...], vals: tuple[Any, ...]) -> None:
        self._cols = cols
        self._vals = vals

    def __getitem__(self, key: Any) -> Any:
        if isinstance(key, int):
            return self._vals[key]
        return self._vals[self._cols.index(key)]

    def keys(self) -> list[str]:
        return list(self._cols)

    def __iter__(self):
        return iter(self._vals)

    def __len__(self) -> int:
        return len(self._vals)


def _pg_row_factory(cursor):
    cols = tuple(d.name for d in (cursor.description or ()))

    def make(values):
        return _PgRow(cols, tuple(values))

    return make


class _PgCursor:
    """psycopg cursor 를 sqlite3.Cursor 처럼 — fetchone/fetchall/lastrowid."""

    __slots__ = ("_cur", "_lastrowid")

    def __init__(self, cur, lastrowid=None) -> None:
        self._cur = cur
        self._lastrowid = lastrowid

    def fetchone(self):
        return self._cur.fetchone()

    def fetchall(self):
        return self._cur.fetchall()

    def __iter__(self):
        return iter(self._cur)

    @property
    def rowcount(self) -> int:
        return self._cur.rowcount

    @property
    def lastrowid(self):
        # v3.57 Phase 3: pg 엔 lastrowid 없음 → _PgConn 이 INSERT 에 RETURNING id 를
        # 자동 부착해 여기 채워둔다 (id 컬럼 있는 테이블만).
        return self._lastrowid


class _PgConn:
    """psycopg connection 을 state.py 의 sqlite3.Connection 사용패턴에 맞춘 어댑터.

    지원: execute(sql, params) / executescript / close / row dual-access / autocommit.
    """

    __slots__ = ("_conn",)

    def __init__(self, conn) -> None:
        self._conn = conn

    @property
    def raw(self):
        """v3.88: 하위 psycopg 연결 (어댑터의 SET LOCAL search_path·advisory lock 용).
        private `_conn` 직접 결합을 피하기 위한 공개 접근점."""
        return self._conn

    def execute(self, sql: str, params: tuple = ()):
        pg_sql = _to_pg_sql(sql, bool(params))
        bind = tuple(params) if params else None
        # INSERT 면 RETURNING id 자동 부착 → lastrowid 호환 (id 컬럼 있는 테이블만).
        m = _PG_INSERT_RE.match(sql)
        if (m and m.group(1).lower() not in _PG_IDLESS_TABLES
                and "returning" not in sql.lower()):
            cur = self._conn.cursor(row_factory=_pg_row_factory)
            cur.execute(pg_sql.rstrip().rstrip(";") + " RETURNING id", bind)
            row = cur.fetchone()
            return _PgCursor(cur, lastrowid=(row[0] if row is not None else None))
        cur = self._conn.cursor(row_factory=_pg_row_factory)
        cur.execute(pg_sql, bind)
        return _PgCursor(cur)

    def executescript(self, script: str) -> None:
        # psycopg execute 는 단일문 위주 — 세미콜론 분리 실행 (스키마 부트스트랩용).
        for stmt in _split_sql_statements(script):
            self._conn.execute(stmt)

    def close(self) -> None:
        self._conn.close()

    def transaction(self):
        """psycopg3 transaction() 위임 — autocommit 연결이라도 BEGIN/COMMIT 블록을
        연다. read-modify-write(finding_upsert/goal_record_turn)를 per-key advisory
        xact lock 과 함께 원자화하는 데 쓴다. xact lock 은 커밋/롤백 시 자동 해제라
        풀에 반환돼도 lock 누수가 없다 (session advisory lock 과 달리)."""
        return self._conn.transaction()


def _split_sql_statements(script: str) -> list[str]:
    """단순 세미콜론 분리 (문자열 리터럴 내 ';' 없다는 전제 — 스키마 DDL 용)."""
    return [s.strip() for s in script.split(";") if s.strip()]


