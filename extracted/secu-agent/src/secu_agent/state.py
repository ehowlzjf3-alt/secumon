def chat_session_list(
    *,
    agent_type: str | None = None,
    include_archived: bool = False,
    limit: int = 100,
) -> list[dict[str, Any]]:
    q = (
        "SELECT cs.*, "
        "(SELECT COUNT(*) FROM chat_message cm WHERE cm.session_id=cs.id) "
        "AS message_count, "
        "(SELECT MAX(created_at) FROM chat_message cm WHERE cm.session_id=cs.id) "
        "AS last_message_at "
        "FROM chat_session cs"
    )
    where: list[str] = []
    args: list[Any] = []
    if agent_type is not None:
        where.append("cs.agent_type=?")
        args.append(agent_type)
    if not include_archived:
        where.append("COALESCE(cs.status, 'active') != 'archived'")
    if where:
        q += " WHERE " + " AND ".join(where)
    # pg 는 ORDER BY 표현식 안에서 SELECT alias(last_message_at) 참조 불가 →
    # 서브쿼리 반복 (sqlite·pg 양쪽 호환).
    q += (
        " ORDER BY COALESCE("
        "(SELECT MAX(created_at) FROM chat_message cm WHERE cm.session_id=cs.id), "
        "cs.updated_at, cs.started_at) DESC LIMIT ?"
    )
    args.append(limit)
    with connect() as c:
        rows = c.execute(q, args).fetchall()
        return [_chat_session_row(r) for r in rows]


def chat_session_update(
    session_id: int,
    *,
    label: str | None = None,
    status: str | None = None,
    settings: dict[str, Any] | None = None,
) -> None:
    allowed_statuses = {"active", "archived"}
    fields: list[str] = []
    args: list[Any] = []
    if label is not None:
        fields.append("label=?")
        args.append(label)
    if settings is not None:
        # v3.82 U5: 전체 교체 (부분 병합 아님 — 호출측이 완성 dict 전달)
        fields.append("settings=?")
        args.append(json.dumps(settings, ensure_ascii=False))
    if status is not None:
        if status not in allowed_statuses:
            raise ValueError(f"invalid chat session status: {status!r}")
        fields.append("status=?")
        args.append(status)
        fields.append("archived_at=?")
        args.append(time.time() if status == "archived" else None)
    if not fields:
        return
    fields.append("updated_at=?")
    args.append(time.time())
    args.append(session_id)
    with connect() as c:
        c.execute(
            f"UPDATE chat_session SET {', '.join(fields)} WHERE id=?",
            args,
        )


def chat_session_delete(session_id: int) -> bool:
    """End a chat session without deleting its persisted history."""
    with connect() as c:
        row = c.execute(
            "SELECT id FROM chat_session WHERE id=?", (session_id,),
        ).fetchone()
        if row is None:
            return False
        now = time.time()
        cur = c.execute(
            "UPDATE chat_session SET status='archived', "
            "archived_at=COALESCE(archived_at, ?), updated_at=? WHERE id=?",
            (now, now, session_id),
        )
        return cur.rowcount > 0


