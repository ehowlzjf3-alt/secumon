# R3-1: 선택적 `schema.` 접두를 (비캡처로) 소비하고 **테이블명**을 group(1)로 캡처.
# 구 정규식은 첫 식별자만 잡아 `INSERT INTO platform.control_flag` 를 테이블명 `platform` 으로 오인 →
# idless 판정을 놓쳐 RETURNING id 를 붙이고 UndefinedColumn:id 로 깨졌다(정규화 컷오버 선행 블로커).
# bare/qualified 둘 다 테이블명이 group(1) → idless 판정 정확. 현행 unqualified 무영향.
# 전제(codex 확인): idless 판정은 bare table-name 조회 → idless 이름이 스키마 간 전역 유일(동명이면서
# id-shape 다른 테이블 충돌 없음)해야 정확하다. 현행/근미래 컷오버 idless 집합은 충족. 장기적으로 id 유무가
# 다른 동명 테이블이 생기면 (schema,table) 키로 승격 필요(ASK R3-1 권고).
# 계약: 비인용 ASCII 1/2-part 식별자(_validate_ident)만 대상 — 뒤 경계 없는 prefix matcher 라
# 3-part·따옴표·`$` suffix 는 비대상(현 명명 규칙상 발생 안 함).
_PG_INSERT_RE = re.compile(
    r"^\s*INSERT\s+INTO\s+(?:[a-zA-Z_][a-zA-Z0-9_]*\s*\.\s*)?([a-zA-Z_][a-zA-Z0-9_]*)",
    re.IGNORECASE,
)


def _to_pg_sql(sql: str, has_params: bool) -> str:
    """sqlite 식 SQL → psycopg(%s) 식.

    - `?` → `%s` (psycopg3 는 `%s` 만 지원).
    - 파라미터가 있을 때만 리터럴 `%` → `%%` 이스케이프 (psycopg 는 params 있을 때만
      `%` 를 특수처리). state.py SQL 엔 리터럴 `%` 없음(LIKE 와일드카드는 바인드 값에
      들어감) — 방어적으로 처리.
    """
    if has_params and "%" in sql:
        sql = sql.replace("%", "%%")
    return sql.replace("?", "%s")


