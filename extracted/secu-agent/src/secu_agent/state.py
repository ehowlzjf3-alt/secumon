# entity_timeline — v3.63 H4 (엔티티 축 cross-table 타임라인)
# ============================================================

# entity 축은 등록형 (v3.85). 코어는 host/domain/url 만 알고, 도메인이 새 축(ip/
# share/repo 등)을 도입하면 register_entity_type 로 등록한다 — 이전엔 하드코딩
# ENTITY_TYPES 튜플이 등록 소스보다 먼저 게이트해, 도메인이 이벤트를 공급해도
# 코어가 그 축을 거부했다(register_memory_scope 와 같은 패턴).
# match 모드: "prefix"(asset 이 eid 로 시작) | "substring"(eid 를 포함).
# 하위호환 공개 심볼 — 도메인 어댑터(skill state_domain 등)가 import 한다. 코어 축
# 튜플. 새 코드는 valid_entity_types() 를 쓰되 이 이름은 back-compat 로 유지한다.
ENTITY_TYPES = ("host", "domain", "url")
_CORE_ENTITY_TYPES: frozenset[str] = frozenset(ENTITY_TYPES)
_CORE_ENTITY_MATCH: dict[str, str] = {
    "host": "prefix", "domain": "substring", "url": "substring",
}
_PLUGIN_ENTITY_TYPES: dict[str, str] = {}


def register_entity_type(key: str, *, match: str = "substring") -> None:
    """timeline 엔티티 축 등록 (plugin API). match ∈ {"prefix","substring"}."""
    k = str(key or "").strip().lower()
    if not k:
        raise ValueError("entity_type 이름 비어 있음")
    if match not in ("prefix", "substring"):
        raise ValueError(f"match 는 'prefix'|'substring' (받음: {match!r})")
    if k not in _CORE_ENTITY_TYPES:
        _PLUGIN_ENTITY_TYPES[k] = match


def unregister_entity_type(key: str) -> bool:
    """등록 해제 (테스트/재부착 멱등용). 코어 축은 제거 불가."""
    k = str(key or "").strip().lower()
    if k in _CORE_ENTITY_TYPES:
        return False
    return _PLUGIN_ENTITY_TYPES.pop(k, None) is not None


def valid_entity_types() -> frozenset[str]:
    return frozenset(_CORE_ENTITY_TYPES | set(_PLUGIN_ENTITY_TYPES))


def _entity_match_mode(etype: str) -> str:
    return _CORE_ENTITY_MATCH.get(etype) or _PLUGIN_ENTITY_TYPES.get(etype, "substring")


def _timeline_findings(c, like: str, events: list[dict[str, Any]]) -> None:
    """finding_lifecycle 에서 asset LIKE 매칭 → 타임라인 이벤트 append."""
    for r in c.execute(
        "SELECT first_seen, severity, summary, status, task_type "
        "FROM finding_lifecycle WHERE asset LIKE ?",
        (like,),
    ).fetchall():
        events.append({
            "ts": r["first_seen"],
            "source": r["task_type"],
            "action": f"finding_{r['status']}",
            "detail": r["summary"],
            "severity": r["severity"],
        })


_TIMELINE_SOURCES: list = []


def register_timeline_source(fn) -> None:
    """plugin 타임라인 소스 등록 (v3.82 U3c). fn(entity_type, entity_id) -> list[dict].

    이벤트 dict = {ts, source, action, detail, severity}. 도메인 테이블 조인
    (구 smb_share/web_target_domain/devops_target 분기)은 도메인 서비스가
    자기 소스를 등록해 재공급한다 — 코어는 finding_lifecycle 만 조회.
    """
    if fn in _TIMELINE_SOURCES:
        raise ValueError("timeline source 이미 등록됨")
    _TIMELINE_SOURCES.append(fn)


def unregister_timeline_source(fn) -> bool:
    try:
        _TIMELINE_SOURCES.remove(fn)
        return True
    except ValueError:
        return False


def entity_timeline(entity_type: str, entity_id: str) -> list[dict[str, Any]]:
    """엔티티(host/domain/url) 하나를 축으로 시간순 사건 집계.

    각 이벤트: {ts, source, action, detail, severity}. ts 오름차순 정렬.
    코어 = finding_lifecycle LIKE 매칭 + 등록된 plugin 소스 (v3.82 U3c).
    """
    etype = (entity_type or "").lower().strip()
    eid = (entity_id or "").strip()
    if etype not in valid_entity_types():
        raise ValueError(
            f"unknown entity_type: {entity_type!r} "
            f"(allowed: {sorted(valid_entity_types())} — 도메인 축은 "
            "register_entity_type 로 등록)"
        )
    events: list[dict[str, Any]] = []
    like = f"{eid}%" if _entity_match_mode(etype) == "prefix" else f"%{eid}%"
    with connect() as c:
        _timeline_findings(c, like, events)
    for fn in _TIMELINE_SOURCES:
        events.extend(fn(etype, eid) or [])
    events.sort(key=lambda e: (e["ts"] if e["ts"] is not None else 0.0))
    return events


