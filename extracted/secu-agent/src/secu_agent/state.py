def chat_messages_for(
    session_id: int, *, limit: int | None = None,
) -> list[dict[str, Any]]:
    """chronological (oldest first). limit 지정 시 가장 최근 N 개의 chronological 순."""
    with connect() as c:
        if limit is None:
            rows = c.execute(
                "SELECT id, role, content, created_at FROM chat_message "
                "WHERE session_id=? ORDER BY id ASC",
                (session_id,),
            ).fetchall()
        else:
            # 최근 N 개 (id DESC) → reverse 로 chronological
            rows = c.execute(
                "SELECT id, role, content, created_at FROM chat_message "
                "WHERE session_id=? ORDER BY id DESC LIMIT ?",
                (session_id, limit),
            ).fetchall()
            rows = list(reversed(rows))
        out = []
        for r in rows:
            d = {k: r[k] for k in r.keys()}
            try:
                d["content"] = json.loads(d["content"])
            except Exception:
                d["content"] = {"text": d["content"]}
            out.append(d)
        return out


