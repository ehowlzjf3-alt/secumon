def _validate_column_names(names: Any) -> None:
    """Raise ValueError 만약 column 이름이 SQL identifier 패턴 안 맞으면."""
    for n in names:
        if not isinstance(n, str) or not _COLUMN_NAME_RE.match(n):
            raise ValueError(f"invalid column name {n!r}")
