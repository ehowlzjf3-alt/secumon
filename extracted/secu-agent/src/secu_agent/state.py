def finding_update(
    finding_id: int,
    *,
    status: str | None = None,
    severity: str | None = None,
    owner: str | None = None,
    ticket_ref: str | None = None,
    sla_due: float | None = None,
    summary: str | None = None,
    evidence_ref: str | None = None,
    extra: dict[str, Any] | None = None,
    merge_extra: bool = True,
) -> None:
    fields: list[str] = []
    args: list[Any] = []
    if status is not None:
        if status not in _FINDING_STATUSES:
            raise ValueError(f"invalid finding status: {status!r}")
        fields.append("status=?")
        args.append(status)
    if severity is not None:
        if severity not in _SEVERITY_RANK:
            raise ValueError(f"invalid severity: {severity!r}")
        fields.append("severity=?")
        args.append(severity)
    if owner is not None:
        fields.append("owner=?")
        args.append(owner)
    if ticket_ref is not None:
        fields.append("ticket_ref=?")
        args.append(ticket_ref)
    if sla_due is not None:
        fields.append("sla_due=?")
        args.append(sla_due)
    if summary is not None:
        fields.append("summary=?")
        args.append(summary)
    if evidence_ref is not None:
        fields.append("evidence_ref=?")
        args.append(evidence_ref)
    if extra is not None:
        next_extra = dict(extra)
        current_extra: dict[str, Any] | None = None
        if merge_extra:
            current = finding_get(finding_id)
            if current is not None:
                current_extra = dict(current.get("extra") or {})
                merged = dict(current_extra)
                merged.update(next_extra)
                next_extra = merged
        next_extra = _merge_agent_observations(next_extra, current_extra)
        fields.append("extra_json=?")
        args.append(json.dumps(next_extra, ensure_ascii=False, sort_keys=True))
    if not fields:
        return
    args.append(finding_id)
    with connect() as c:
        c.execute(
            f"UPDATE finding_lifecycle SET {', '.join(fields)} WHERE id=?",
            args,
        )


