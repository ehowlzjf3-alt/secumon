def _env_int(name: str, default: int, *, minimum: int = 1) -> int:
    """SA_* 정수 env 파싱 — 미설정/파싱실패/하한미만이면 안전 기본값 폴백."""
    raw = os.environ.get(name)
    if raw is None or not raw.strip():
        return default
    try:
        val = int(raw.strip())
    except (TypeError, ValueError):
        log.warning("%s=%r 정수 파싱 실패 — 기본값 %d 사용", name, raw, default)
        return default
    if val < minimum:
        log.warning("%s=%d < 하한 %d — 기본값 %d 사용", name, val, minimum, default)
        return default
    return val


