def _schedule_fire_select() -> str:
    return (
        "SELECT sf.*, "
        "s.agent_type AS agent_type, s.prompt AS schedule_prompt, "
        "s.cron_expr AS cron_expr, s.status AS schedule_status, "
        "s.origin AS origin, s.deliver AS deliver, s.repeat AS repeat, "
        "s.fire_count AS schedule_fire_count, s.next_run AS next_run, "
        "s.last_run AS last_run, s.charter_ref AS charter_ref, "
        "s.created_by AS created_by, s.schedule_kind AS schedule_kind, "
        "s.stale_policy AS stale_policy, "
        "s.source_session_id AS source_session_id, "
        "s.source_message_id AS source_message_id, "
        "s.expires_at AS expires_at, "
        "COUNT(sd.id) AS delivery_count "
        "FROM schedule_fire sf "
        "JOIN schedule s ON s.id=sf.schedule_id "
        "LEFT JOIN schedule_delivery sd ON sd.fire_id=sf.id"
    )


def schedule_fire_history(
    *,
    agent_type: str | None = None,
    status: str | None = None,
    limit: int = 50,
) -> list[dict[str, Any]]:
    where: list[str] = []
    args: list[Any] = []
    if agent_type:
        where.append("s.agent_type=?")
        args.append(agent_type)
    if status:
        where.append("sf.status=?")
        args.append(status)
    q = _schedule_fire_select()
    if where:
        q += " WHERE " + " AND ".join(where)
    # pg 는 GROUP BY 에 PK 만 있으면 그 테이블 컬럼 selectable — sf.id + s.id 둘 다
    # 그룹해야 s.* (JOIN한 schedule) 컬럼이 functional-dependent 로 허용됨.
    q += " GROUP BY sf.id, s.id ORDER BY sf.id DESC LIMIT ?"
    args.append(limit)
    with connect() as c:
        rows = c.execute(q, args).fetchall()
        return [{k: r[k] for k in r.keys()} for r in rows]


def schedule_fire_get(fire_id: int) -> dict[str, Any] | None:
    q = _schedule_fire_select() + " WHERE sf.id=? GROUP BY sf.id, s.id"
    with connect() as c:
        r = c.execute(q, (fire_id,)).fetchone()
        return {k: r[k] for k in r.keys()} if r else None


