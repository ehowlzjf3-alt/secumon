def goal_record_turn(
    goal_id: int, *, verdict: str | None, reason: str | None,
    parse_fail: bool | None,
    progress: bool | None = None,
) -> dict[str, int]:
    """turn 진행 기록 + streak 갱신. 반환 = 갱신 후 streak 2종.

    parse_fail: True=streak+1 / False=0 리셋 / None=보존.
      v3.81 T1a: judge 를 건너뛴 게이트 턴은 None 이어야 한다 — False 로
      리셋하면 judge_every>1 에서 게이트 턴들이 매번 streak 을 지워
      parse-fail 3x 탈출구가 영원히 발동 못 함 (termination_gap).
    progress: True=no_progress_streak 0 리셋 / False=+1 / None=보존.
      judge 가 실제 평가한 턴만 True/False — 게이트/parse-fail 턴은 None.
    """
    with connect() as c:
        # streak(parse_fail/no_progress)은 SELECT-후-UPDATE read-modify-write 다.
        # fanout 이 완료마다 asyncio.to_thread(goal_record_turn) 로 기록하고 부모 루프도
        # 같은 goal 을 갱신할 수 있어, 동시 진입 시 lost update 로 streak 이 과소집계되면
        # termination_gap 안전종료(parse-fail 3x / no-progress N)가 늦게 발동한다.
        # per-goal advisory xact lock 으로 read-modify-write 를 직렬화 (커밋 시 자동해제).
        with c.transaction():
            c.execute("SELECT pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext(?))", (f"goal:{goal_id}",))
            r = c.execute(
                "SELECT parse_fail_streak, no_progress_streak "
                "FROM chat_goal WHERE id=?",
                (goal_id,),
            ).fetchone()
            prev_pf = int(r["parse_fail_streak"]) if r else 0
            prev_np = int(r["no_progress_streak"]) if r else 0
            if parse_fail is None:
                new_pf = prev_pf
            else:
                new_pf = (prev_pf + 1) if parse_fail else 0
            if progress is None:
                new_np = prev_np
            else:
                new_np = 0 if progress else (prev_np + 1)
            c.execute(
                "UPDATE chat_goal SET turns_used=turns_used+1, "
                "last_verdict=?, last_reason=?, parse_fail_streak=?, "
                "no_progress_streak=?, updated_at=? "
                "WHERE id=?",
                (verdict, reason, new_pf, new_np, time.time(), goal_id),
            )
    return {"parse_fail_streak": new_pf, "no_progress_streak": new_np}


