_SEVERITY_RANK = {
    "informational": 0,
    "low": 1,
    "medium": 2,
    "high": 3,
    "critical": 4,
}
_FINDING_STATUSES = {
    "open",
    "triaged",
    "false_positive",
    "accepted_risk",
    "remediated",
}


def finding_fingerprint(
    *, task_type: str, asset: str, asset_kind: str, discriminator: str = "",
) -> str:
    # discriminator: 같은 asset 에서 성격이 다른 발견을 분리하기 위한 키 (예: hit
    # category+kind 시그니처). 빈 문자열이면 기존(task_type+asset+asset_kind) 동작.
    parts = [task_type.strip(), asset.strip(), asset_kind.strip()]
    if discriminator.strip():
        parts.append(discriminator.strip())
    raw = "\n".join(parts)
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def _finding_row(r) -> dict[str, Any] | None:
    if r is None:
        return None
    d = {k: r[k] for k in r.keys()}
    try:
        d["extra"] = json.loads(d.pop("extra_json") or "{}")
    except Exception:
        d["extra"] = {}
    return d


def _load_finding_extra(raw: str | None) -> dict[str, Any]:
    try:
        parsed = json.loads(raw or "{}")
    except Exception:
        return {}
    return parsed if isinstance(parsed, dict) else {}


def _agent_provenance_key(provenance: dict[str, Any]) -> tuple[str, ...]:
    return tuple(
        str(provenance.get(key, "") or "")
        for key in ("session_id", "agent_type", "llm_profile", "llm_client", "llm_model")
    )


def _merge_agent_observations(
    next_extra: dict[str, Any],
    previous_extra: dict[str, Any] | None,
) -> dict[str, Any]:
    """Preserve which agents observed a deduped finding without merging all extra."""
    prev = previous_extra or {}
    has_provenance = (
        isinstance(next_extra.get("agent_provenance"), dict)
        or isinstance(prev.get("agent_provenance"), dict)
        or isinstance(next_extra.get("agent_observations"), list)
        or isinstance(prev.get("agent_observations"), list)
    )
    if not has_provenance:
        return next_extra

    out = dict(next_extra)
    observations: list[dict[str, Any]] = []
    seen: set[tuple[str, ...]] = set()

    def add(provenance: object) -> None:
        if not isinstance(provenance, dict):
            return
        cleaned = {str(k): v for k, v in provenance.items() if v not in (None, "", [])}
        if not cleaned:
            return
        key = _agent_provenance_key(cleaned)
        if key in seen:
            return
        seen.add(key)
        observations.append(cleaned)

    for item in prev.get("agent_observations") or []:
        add(item)
    add(prev.get("agent_provenance"))
    for item in next_extra.get("agent_observations") or []:
        add(item)
    add(next_extra.get("agent_provenance"))
    if observations:
        out["agent_observations"] = observations[-20:]
    return out


def finding_upsert(
    *,
    task_type: str,
    asset: str,
    asset_kind: str,
    severity: str,
    summary: str,
    fingerprint: str | None = None,
    owner: str | None = None,
    ticket_ref: str | None = None,
    sla_due: float | None = None,
    evidence_ref: str | None = None,
    extra: dict[str, Any] | None = None,
) -> tuple[int, bool]:
    if severity not in _SEVERITY_RANK:
        raise ValueError(f"invalid severity: {severity!r}")
    fp = fingerprint or finding_fingerprint(
        task_type=task_type, asset=asset, asset_kind=asset_kind,
    )
    now = time.time()
    next_extra = _merge_agent_observations(dict(extra or {}), None)
    extra_json = json.dumps(next_extra, ensure_ascii=False, sort_keys=True)
    with connect() as c:
        # 원자적 upsert. fingerprint 는 UNIQUE — SELECT-후-INSERT/UPDATE 사이에 동일
        # fp 로 동시 진입하면 (a) 두 번째 INSERT 가 UNIQUE 위반으로 크래시하고,
        # (b) 두 UPDATE 가 extra_json read-modify-write 를 서로 덮어써 agent 관측을
        # 유실한다. per-fingerprint advisory xact lock 으로 직렬화한다(트랜잭션 종료 시
        # 자동 해제 → 풀 반환돼도 누수 없음). autocommit 이라도 transaction() 이 BEGIN.
        with c.transaction():
            c.execute("SELECT pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext(?))", (f"finding:{fp}",))
            row = c.execute(
                "SELECT id, severity, owner, ticket_ref, sla_due, evidence_ref, "
                "seen_count, extra_json "
                "FROM finding_lifecycle WHERE fingerprint=?",
                (fp,),
            ).fetchone()
            if row:
                previous_extra = _load_finding_extra(row["extra_json"])
                next_extra = _merge_agent_observations(dict(extra or {}), previous_extra)
                extra_json = json.dumps(next_extra, ensure_ascii=False, sort_keys=True)
                existing_sev = row["severity"]
                worst = (
                    severity if _SEVERITY_RANK[severity] >= _SEVERITY_RANK[existing_sev]
                    else existing_sev
                )
                c.execute(
                    "UPDATE finding_lifecycle SET task_type=?, asset=?, asset_kind=?, "
                    "severity=?, summary=?, owner=?, ticket_ref=?, sla_due=?, "
                    "evidence_ref=?, last_seen=?, seen_count=seen_count+1, extra_json=? "
                    "WHERE id=?",
                    (
                        task_type, asset, asset_kind, worst, summary,
                        owner if owner is not None else row["owner"],
                        ticket_ref if ticket_ref is not None else row["ticket_ref"],
                        sla_due if sla_due is not None else row["sla_due"],
                        evidence_ref if evidence_ref is not None else row["evidence_ref"],
                        now, extra_json, row["id"],
                    ),
                )
                return int(row["id"]), False
            cur = c.execute(
                "INSERT INTO finding_lifecycle("
                "fingerprint, task_type, asset, asset_kind, severity, summary, status, "
                "owner, ticket_ref, sla_due, evidence_ref, first_seen, last_seen, "
                "seen_count, extra_json"
                ") VALUES (?, ?, ?, ?, ?, ?, 'open', ?, ?, ?, ?, ?, ?, 1, ?)",
                (
                    fp, task_type, asset, asset_kind, severity, summary,
                    owner, ticket_ref, sla_due, evidence_ref, now, now, extra_json,
                ),
            )
            return int(cur.lastrowid), True


