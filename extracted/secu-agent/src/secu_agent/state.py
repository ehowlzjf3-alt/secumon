def db_label() -> str:
    """진단/로그용 DB 식별 문자열 — 비밀번호는 마스킹. (v3.76: 단일 postgres)"""
    dsn = os.environ.get("SECU_AGENT_PG_DSN") or ""
    if not dsn:
        return "postgres"
    try:
        from urllib.parse import urlsplit
        p = urlsplit(dsn)
        host = p.hostname or "?"
        port = f":{p.port}" if p.port else ""
        name = (p.path or "").lstrip("/") or "?"
        return f"postgres://{host}{port}/{name}"
    except Exception:
        return "postgres"


def _pg_dsn() -> str:
    dsn = os.environ.get("SECU_AGENT_PG_DSN")
    if not dsn:
        raise RuntimeError(
            "SECU_AGENT_DB_BACKEND=postgres 인데 SECU_AGENT_PG_DSN 없음. "
            ".env 에 postgresql://user:pass@host:5432/dbname 형식으로 설정."
        )
    return dsn


